export function rigSourceText(value: string | undefined, zh = true): string {
  return value ? (zh ? (chinese[value] ?? value) : value) : ''
}

export function rigSourcePropertyText({ options: o }: SourceLayout, zh: boolean) {
  return rigSourceText(
    zh && o.owner === 'cameraData' && o.property === 'shift_y'
      ? 'Shift Y'
      : (o.text ?? o.rna?.name),
    zh,
  )
}
