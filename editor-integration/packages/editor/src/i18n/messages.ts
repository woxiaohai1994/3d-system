export type MessageId = keyof typeof zhCN
export const SUPPORTED_LOCALES = [
  { id: 'zh-CN', name: '简体中文' },
  { id: 'en', name: 'English' },
] as const
export type Locale = (typeof SUPPORTED_LOCALES)[number]['id']
export type MessageValues = Record<string, string | number>
export const DEFAULT_LOCALE: Locale = 'zh-CN'

export function isLocale(value: unknown): value is Locale {
  return SUPPORTED_LOCALES.some((locale) => locale.id === value)
}

export function translate(locale: Locale, key: MessageId, values: MessageValues = {}): string {
  const message = locale === 'zh-CN' ? zhCN[key] : key
  return message.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : match,
  )
}

// Only use for application-owned presentation labels, never scene or user names.
export function translateLabel(locale: Locale, label: string): string {
  return Object.hasOwn(zhCN, label) ? translate(locale, label as MessageId) : label
}
