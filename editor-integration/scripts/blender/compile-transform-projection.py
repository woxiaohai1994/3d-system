"""Extract the VIEW3D transform-center projection from the pinned Blender source."""
from pathlib import Path
import hashlib
import json
import re
import subprocess

ROOT = Path(__file__).resolve().parents[2]
hashes = {}


def read(directory, name):
    path = ROOT / 'vendor' / directory / name
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    assert json.loads((path.parent / 'UPSTREAM.json').read_text())['files'][name]['sha256'] == digest
    hashes[directory + '/' + name] = digest
    return path.read_text()


projection = read('blender-transform-translation', 'view3d_project.cc')
transform = read('blender-transform-constraints', 'transform.cc')
matrix = read('blender-transform-translation', 'math_matrix_c.cc')
assert 'mul_m4_v4(perspmat, vec4);' in projection
assert 'R[0][0] = B[0][0] * A[0][0] + B[0][1] * A[1][0] + B[0][2] * A[2][0] + B[0][3] * A[3][0];' in matrix
assert 'r[0] = x * mat[0][0] + y * mat[1][0] + z * mat[2][0] + mat[3][0] * v[3];' in matrix
zero = re.search(r'#define BL_ZERO_CLIP ([\d.]+)', projection).group(1)
start = projection.index('const float w = fabsf(vec4[3]);')
end = projection.index('return V3D_PROJ_RET_OK;', start)
body = projection[start:end]
# Only NOP and CLIP_ZERO are used by transform centers/cursors. BB/near/far/window
# clipping belongs to scene picking and must not clip a transform pivot.
body = re.sub(r'  if \(\(flag & V3D_PROJ_TEST_CLIP_(?:NEAR|FAR|WIN)\).*?\n  }\n', '', body, flags=re.S)
body = body.replace('(flag & V3D_PROJ_TEST_CLIP_ZERO)', 'clipZero')
body = body.replace('return V3D_PROJ_RET_CLIP_ZERO;', 'return [width / 2, height / 2]')
body = body.replace('float(BL_ZERO_CLIP)', zero).replace('fabsf(', 'Math.abs(')
body = body.replace('float(region->winx)', 'width').replace('float(region->winy)', 'height')
body = re.sub(r'\b(\d+\.\d+)f\b', r'\1', body)
body = body.replace('const float ', 'const ').replace(' != ', ' !== ')
body = body.replace('Math.abs(vec4[3])', 'Math.abs(f(vec4[3]))')
body = body.replace('1.0 / w', 'f(1.0 / w)')
body = body.replace('(width / 2.0) * (1.0 + vec4[0] * scalar)', 'f(f(f(width) / 2.0) * f(1.0 + f(f(vec4[0]) * scalar)))')
body = body.replace('(height / 2.0) * (1.0 + vec4[1] * scalar)', 'f(f(f(height) / 2.0) * f(1.0 + f(f(vec4[1]) * scalar)))')
body = body.replace('r_co[0] = fx;', '').replace('r_co[1] = fy;', '')
assert 'adr[0] = t->region->winx / 2.0f;' in transform
assert 'adr[1] = t->region->winy / 2.0f;' in transform
assert 'isfinite(tvec[0]) && isfinite(tvec[1])' in projection
output = ROOT / 'packages/editor/src/components/scene-camera/rig-transform-projection-source.ts'
output.write_text('''// SPDX-License-Identifier: GPL-2.0-or-later
// Generated by scripts/blender/compile-transform-projection.py; do not edit.
export const sourceProjectionHashes = ''' + json.dumps(hashes, indent=2) + '''
const f = Math.fround
const add4 = (a: number, b: number, c: number, d: number) => f(f(f(a + b) + c) + d)

export function sourceProjectTransformClip(
  projection: readonly number[],
  view: readonly number[],
  point: readonly number[],
): [number, number, number, number] {
  const a = projection.map(f), b = view.map(f), matrix = new Array<number>(16)
  // Blender forms one float perspective matrix before multiplying a float point.
  // Applying two double matrices separately retains a false non-zero optical depth.
  for (let column = 0; column < 4; column++)
    for (let row = 0; row < 4; row++)
      matrix[column * 4 + row] = add4(
        f(b[column * 4]! * a[row]!),
        f(b[column * 4 + 1]! * a[4 + row]!),
        f(b[column * 4 + 2]! * a[8 + row]!),
        f(b[column * 4 + 3]! * a[12 + row]!),
      )
  const [x, y, z] = point.map(f)
  return [0, 1, 2, 3].map((row) => add4(
    f(x! * matrix[row]!), f(y! * matrix[4 + row]!),
    f(z! * matrix[8 + row]!), matrix[12 + row]!,
  )) as [number, number, number, number]
}

export function sourceProjectTransformCenter(
  vec4: [number, number, number, number],
  width: number,
  height: number,
  clipZero = false,
): [number, number] {
''' + body + '''
  return Number.isFinite(fx) && Number.isFinite(fy) ? [fx, fy] : [width / 2, height / 2]
}
''')
subprocess.run([str(ROOT / 'node_modules/.bin/biome'), 'check', '--write', str(output)], check=True, cwd=ROOT)
print('Extracted native center projection with zero-depth and behind-view behavior')
