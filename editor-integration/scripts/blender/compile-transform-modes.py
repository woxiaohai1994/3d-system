"""Compile Blender's channel-lock functions and read its modal orientation calls."""
from pathlib import Path
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[2]
vendor = ROOT / 'vendor/blender-transform-modes'
source = (vendor / 'transform_mode.cc').read_text()
header = (vendor / 'DNA_object_types.h').read_text()


def function_body(text, name):
    start = re.search(r'\b' + name + r'\s*\([^)]*\)\s*\{', text).end()
    end, depth = start, 1
    while depth:
        depth += (text[end] == '{') - (text[end] == '}')
        end += 1
    return text[start:end - 1]


signatures = {
    'protectedTransBits': 'protectflag: number, vec: number[]',
    'protectedRotateBits': 'protectflag: number, eul: number[], oldeul: readonly [number, number, number]',
    'protectedSizeBits': 'protectflag: number, size: number[]',
}
parts = ['// SPDX-License-Identifier: GPL-2.0-or-later',
         '// Generated by scripts/blender/compile-transform-modes.py; do not edit.']
for name, shift in re.findall(r'(OB_LOCK_(?:LOC|ROT|SCALE)[XYZ])\s*=\s*1\s*<<\s*(\d+)', header):
    parts.append(f'export const {name} = 1 << {shift}')
parts.append('export const sourceChannelLockBits = {' + ', '.join(
    mode + ': [' + ', '.join('OB_LOCK_' + prefix + axis for axis in 'XYZ') + ']'
    for mode, prefix in [('translate', 'LOC'), ('rotate', 'ROT'), ('scale', 'SCALE')]
) + '} as const')
for name, signature in signatures.items():
    body = function_body(source, name)
    # These three source functions use only conditions and indexed assignments.
    # Fail instead of silently translating a newly introduced C++ construct.
    assert re.fullmatch(r'[\s\w&()\[\]{}=.;]+', body), name
    body = re.sub(r'(\d+\.\d+)f\b', r'\1', body)
    parts.append(f'export function {name}({signature}) {{{body}}}')
orientations = {}
for mode, file_mode, function in [('translate', 'translate', 'initTranslation'),
                                  ('rotate', 'rotate', 'initRotation'),
                                  ('scale', 'resize', 'initResize')]:
    body = function_body((vendor / f'transform_mode_{file_mode}.cc').read_text(), function)
    expression = re.search(r'transform_mode_default_modal_orientation_set\(\s*t,\s*(.*?)\);', body, re.S)[1]
    # CTX_CAMERA is camera-view navigation; source rig editing is CTX_POSE_BONE.
    if 'CTX_CAMERA' in expression:
        assert expression.strip() == '(t->options & CTX_CAMERA) ? V3D_ORIENT_VIEW : V3D_ORIENT_GLOBAL'
        expression = expression.rsplit(':', 1)[1].strip()
    assert expression in ['V3D_ORIENT_GLOBAL', 'V3D_ORIENT_VIEW']
    orientations[mode] = expression.removeprefix('V3D_ORIENT_')
parts.append('export const sourceModalOrientations = ' + json.dumps(orientations) + ' as const')
hashes = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
          for p in sorted(vendor.iterdir()) if p.suffix in ['.h', '.cc']}
parts.append('export const sourceTransformModeHashes = ' + json.dumps(hashes) + ' as const')
(ROOT / 'packages/editor/src/components/scene-camera/rig-transform-modes-source.ts').write_text('\n\n'.join(parts) + '\n')
print('Compiled three source channel-lock functions and pose modal orientations')
