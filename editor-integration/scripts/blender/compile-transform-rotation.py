"""Translate the original compatible Euler conversion and pose rotation branch."""
from pathlib import Path
import hashlib
import json
import re
import subprocess

ROOT = Path(__file__).resolve().parents[2]
hashes = {}


def read(directory, name):
    path = ROOT / 'vendor' / directory / name
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    assert digest == json.loads((path.parent / 'UPSTREAM.json').read_text())['files'][name]['sha256']
    hashes[directory + '/' + name] = digest
    return path.read_text()


def extract(source, name):
    match = re.search(r'^(?:static )?(?:void|float) ' + name + r'\([^;{]+\)\s*\{', source, re.M)
    assert match, name
    start, end, depth = match.start(), match.end(), 1
    while depth:
        depth += (source[end] == '{') - (source[end] == '}')
        end += 1
    return source[start:end]


math = read('blender-transform-rotation', 'math_rotation.c')
mode = read('blender-transform-modes', 'transform_mode.cc')
rotate = read('blender-transform-modes', 'transform_mode_rotate.cc')
signatures = {
    'compatible_eul': 'eul: V3, oldrot: V3',
    'mat3_normalized_to_eulo2': 'mat: M3, eul1: V3, eul2: V3, order: number',
    'mat3_normalized_to_compatible_eulO': 'eul: V3, oldrot: V3, order: number, mat: M3',
    'mat3_to_compatible_eulO': 'eul: V3, oldrot: V3, order: number, mat: M3',
    'large_rotation_limit': 'angle: number',
}


def translate(body):
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S).replace('->', '.')
    body = body.replace('const RotOrderInfo *R', 'const R')
    body = body.replace('float eul1[3], eul2[3];', 'const eul1: V3 = [0,0,0], eul2: V3 = [0,0,0];')
    body = body.replace('float deul[3];', 'const deul: V3 = [0,0,0];')
    body = body.replace('float unit_mat[3][3];', 'const unit_mat: M3 = [[0,0,0],[0,0,0],[0,0,0]];')
    body = body.replace('float d1, d2;', 'let d1: number, d2: number;').replace('float cy;', 'let cy: number;')
    body = body.replace('uint i;', 'let i: number;')
    body = re.sub(r'\b(?:uint|short) ', 'let ', body)
    body = body.replace('const float ', 'const ').replace('(float)M_PI', 'Math.fround(Math.PI)')
    body = body.replace('(float)EULER_HYPOT_EPSILON', 'EULER_HYPOT_EPSILON')
    body = body.replace('float(', 'Math.fround(')
    body = re.sub(r'\bfloat ', 'let ', body)
    body = re.sub(r'\b(\d+(?:\.\d+)?)f\b', r'\1', body)
    body = body.replace('M_PI_2', '(Math.PI / 2)').replace('M_PI', 'Math.PI')
    body = body.replace('BLI_ASSERT_UNIT_M3(mat);', '')
    body = body.replace('fabsf(', 'Math.abs(').replace('floorf(', 'Math.floor(')
    body = re.sub(r'\[([ijk012])\]', r'[\1]!', body)
    body = body.replace('const pi_x2 = (2.0 * Math.fround(Math.PI));', 'const pi_x2 = Math.fround(2.0 * Math.fround(Math.PI));')
    return body


functions = []
for name, args in signatures.items():
    source = extract(rotate if name == 'large_rotation_limit' else math, name)
    body = translate(source[source.index('{'):])
    functions.append(f'export function {name}({args}) ' + body)

orders = re.search(r'static const RotOrderInfo rotOrders\[\] = \{(.*?)\n\};', math, re.S).group(1)
orders = [[int(x) for x in match] for match in re.findall(r'\{\{(\d), (\d), (\d)\}, (\d)\}', orders)]
epsilon = re.search(r'#define EULER_HYPOT_EPSILON ([^\n]+)', math).group(1)
pose_start = mode.index('float eulmat[3][3];', mode.index('else if (t->options & CTX_POSE_BONE)', mode.index('void ElementRotation_ex')))
pose_end = mode.index('copy_v3_v3(td->ext->rot, eul);', pose_start) + len('copy_v3_v3(td->ext->rot, eul);')
pose = mode[pose_start:pose_end].replace('float eulmat[3][3];', 'const eulmat = new Matrix3();')
pose = translate(pose)
loop_start = rotate.index('    for (float angle_progress = angle_step;')
loop_end = rotate.index('    rmat_cache_reset(rmc);', loop_start)
loop = rotate[loop_start:loop_end]
loop = loop.replace('axis_angle_normalized_to_mat3(rmc->mat, axis_final, angle_progress);', '')
loop = loop.replace('ElementRotation(t, tc, td, rmc->mat, t->around);', 'apply(angle_progress);')
loop = translate(loop).replace('angle_progress += angle_step', 'angle_progress = Math.fround(angle_progress + angle_step)')
step = re.search(r'const float angle_step = ([^;]+);', rotate).group(1)
step = translate(step)
header = '''// SPDX-License-Identifier: GPL-2.0-or-later
// Generated by scripts/blender/compile-transform-rotation.py; do not edit.
import { Euler, Matrix3, Matrix4, Vector3 } from 'three'
import { protectedRotateBits } from './rig-transform-modes-source'
type V3 = [number, number, number]
type M3 = [V3, V3, V3]
const hypotf = (x: number, y: number) => Math.fround(Math.hypot(x, y))
const atan2f = (x: number, y: number) => Math.fround(Math.atan2(x, y))
const fmodf = (x: number, y: number) => Math.fround(x % y)
function copy_v3_v3(out: V3, input: V3) { out.splice(0, 3, ...input) }
function negate_v3(v: V3) { for (let i = 0; i < 3; i++) v[i] = -v[i]! }
function normalize_m3_m3(out: M3, input: M3) {
  for (let i = 0; i < 3; i++) out[i] = new Vector3(...input[i]!).normalize().toArray()
}
function mul_m3_m3m3(out: Matrix3, a: Matrix3, b: Matrix3) { out.multiplyMatrices(a, b) }
function eulO_to_mat3(out: Matrix3, e: V3, _order: number) {
  out.setFromMatrix4(new Matrix4().makeRotationFromEuler(new Euler(...e, 'ZYX')))
}
function sourceMatrixEuler(out: V3, previous: V3, order: number, mat: Matrix3) {
  const e = mat.elements
  mat3_to_compatible_eulO(out, previous, order, [[e[0],e[1],e[2]],[e[3],e[4],e[5]],[e[6],e[7],e[8]]])
}
'''
pose = pose.replace('mat3_to_compatible_eulO(eul,', 'sourceMatrixEuler(eul,')
footer = '''
export function sourcePoseRotation(initial: V3, previous: V3, mat: Matrix3, basis: Matrix3, protectflag: number): V3 {
 const eul: V3 = [0,0,0], totmat = new Matrix3(), smat = new Matrix3(), fmat = new Matrix3()
 const td = { protectflag, ext: { r_mtx: basis, r_smtx: basis.clone().invert(), irot: initial, rot: [...previous] as V3, rotOrder: 1 } }
''' + pose + '\n return td.ext.rot\n}\n'
footer += '''export function sourceNumericRotationSteps(angle_final: number, apply: (angle: number) => void) {
 const angle_sign = angle_final < 0 ? -1 : 1
 const angle_step = ''' + step + '\n' + loop + '\n apply(angle_final)\n}\n'
out = ROOT / 'packages/editor/src/components/scene-camera/rig-transform-rotation-source.ts'
out.write_text(header + f'export const sourceRotationHashes = {json.dumps(hashes, indent=2)}\n'
               + f'const EULER_HYPOT_EPSILON = Math.fround({epsilon})\n'
               + f'const rotOrders = {json.dumps(orders)}\n'
               + 'function get_rotation_order_info(order: number) { const r = rotOrders[Math.max(0, Math.min(5, order - 1))]!; return { axis: r.slice(0,3), parity: r[3] } }\n'
               + '\n'.join(functions) + footer)
subprocess.run([str(ROOT / 'node_modules/.bin/biome'), 'check', '--write', str(out)], check=True, cwd=ROOT)
print('Compiled original compatible Euler, pose rotation, large rotation limit and numeric stepping')
