'''
out = ROOT / 'packages/editor/src/components/scene-camera/rig-transform-pivot-source.ts'
out.write_text(header + body + '\n return td.loc\n}\nexport const sourcePosePivotHash = ' + json.dumps(digest) + '\n')
subprocess.run([str(ROOT / 'node_modules/.bin/biome'), 'format', '--write', str(out)], check=True)
print('Compiled source pose rotation location block')
# Compile the source resize translation branch separately, retaining its pose-space ordering.
resize = source[source.index('void ElementResize('):]
a = resize.index('  if (t->flag & T_POINTS)', resize.index('/* For individual element center'))
b = resize.index('  /* Grease pencil falloff.', a)
c = resize.index('  if (t->options & (CTX_OBJECT | CTX_POSE_BONE))', b)
d = resize.index('\n}', c)
scale_body = resize[a:b] + '  mul_v3_fl(vec, td.factor);\n' + resize[c:d]
scale_body = re.sub(r'/\*.*?\*/', '', scale_body, flags=re.S).replace('->', '.')
scale_body = scale_body.replace('tc.poseobj.object_to_world().ptr()', 'armature')
scale_header = '''
