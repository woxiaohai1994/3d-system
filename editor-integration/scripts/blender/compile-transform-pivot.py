with out.open('a') as f: f.write(scale_header + scale_body + '\n return td.loc\n}\n')
snap_path = ROOT / 'vendor/blender-transform-pivot/view3d_snap.cc'
assert hashlib.sha256(snap_path.read_bytes()).hexdigest() == json.loads((snap_path.parent / 'UPSTREAM.json').read_text())['files'][snap_path.name]['sha256']
snap = snap_path.read_text()
a = snap.index('copy_v3_v3(vec, pchan->pose_head);', snap.index('static bool snap_curs_to_sel_ex(bContext *C, const int pivot_point, float r_cursor[3])\n{'))
b = snap.index('count++;', a) + len('count++;')
body = snap[a:b].replace('pchan->pose_head', 'point').replace('obact_eval->object_to_world().ptr()', 'world')
a = snap.index('  if (count == 0)', b); b = snap.index('\n}', a)
end_body = snap[a:b].replace('return false;', 'return null;').replace('return true;', 'return r_cursor;').replace('float(count)', 'count').replace('1.0f', '1').replace(' == ', ' === ')
