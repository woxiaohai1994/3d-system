"""Extract Blender's cumulative angle input and compile its native reference paths."""
from pathlib import Path
import hashlib
import json
import math
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
hashes = {}


def read(directory, name):
    path = ROOT / 'vendor' / directory / name
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    upstream = json.loads((path.parent / 'UPSTREAM.json').read_text())
    assert digest == upstream['files'][name]['sha256']
    hashes[directory + '/' + name] = digest
    return path.read_text()


def extract(source, name):
    match = re.search(r'^(?:MINLINE |static )?(?:void|float) ' + name + r'\([^;{]+\)\s*\{', source, re.M)
    assert match, name
    start, end, depth = match.start(), match.end(), 1
    while depth:
        depth += (source[end] == '{') - (source[end] == '}')
        end += 1
    return source[start:end]


source = read('blender-transform-modes', 'transform_input.cc')
constraints = read('blender-transform-constraints', 'transform_constraints.cc')
vector = read('blender-transform-angle', 'math_vector.c')
inline = read('blender-transform-angle', 'math_vector_inline.c')
safe = read('blender-transform-angle', 'math_base_safe_inline.c')
original = extract(source, 'InputAngle')
translated = re.sub(r'static void InputAngle\([^\{]+\)',
                    'export function InputAngle(_t: unknown, mi: AngleMouseInput, mval: readonly [number, number], output: [number, number, number])', original)
translated = translated.replace('InputAngle_Data *data = static_cast<InputAngle_Data *>(mi->data);', 'const data = mi.data;')
translated = translated.replace('float dir_prev[2], dir_curr[2], mi_center[2];',
                                'const dir_prev: Vec2 = [0, 0], dir_curr: Vec2 = [0, 0], mi_center: Vec2 = [0, 0];')
translated = re.sub(r'blender::float2\{([^}]+)\}', r'[\1]', translated)
translated = translated.replace('float dphi =', 'let dphi =').replace('->', '.')
translated = re.sub(r'\bfloat\(', 'Math.fround(', translated)
translated = re.sub(r'\bdouble\(', 'Number(', translated)
translated = re.sub(r'(\d+\.\d+)f\b', r'\1', translated)
translated = translated.replace('output[0] = data.angle;', 'output[0] = Math.fround(data.angle);')
precision = re.search(r'case INPUT_ANGLE:.*?precision_factor = ([^;]+);', source, re.S).group(1)
precision = re.sub(r'(\d+\.\d+)f\b', r'\1', precision)
flip = re.search(r'if \(dot_v3v3\(r_axis, view_vector\) > 0.0f\) \{[^}]+\}', constraints).group(0)
flip = flip.replace('dot_v3v3(r_axis, view_vector)', 'axisDotView').replace('0.0f', '0')
flip = flip.replace('*r_angle', 'angle')
flip = 'export function sourceRotationAngleFlip(angle: number, axisDotView: number) {\n' + flip + '\nreturn angle;\n}\n'

# Float adapters for the original BLI helpers below; intermediate rounding matters
# near the pivot and the antipodal boundary, not just at output assignment.
adapters = '''type Vec2 = [number, number]
const f = Math.fround
const copy_v2_v2 = (r: Vec2, a: Vec2) => { r[0] = a[0]; r[1] = a[1] }
const sub_v2_v2v2 = (r: Vec2, a: Vec2, b: Vec2) => { r[0] = f(a[0] - b[0]); r[1] = f(a[1] - b[1]) }
const dot_v2v2 = (a: Vec2, b: Vec2) => f(f(a[0] * b[0]) + f(a[1] * b[1]))
const cross_v2v2 = (a: Vec2, b: Vec2) => f(f(a[0] * b[1]) - f(a[1] * b[0]))
function normalize_v2(a: Vec2) {
  let d = dot_v2v2(a, a)
  if (d > f(1.0e-35)) {
    d = f(Math.sqrt(d))
    const factor = f(1 / d)
    a[0] = f(a[0] * factor); a[1] = f(a[1] * factor)
  } else { a[0] = a[1] = d = 0 }
  return d
}
const len_v2v2 = (a: Vec2, b: Vec2) => {
  const x = f(a[0] - b[0]), y = f(a[1] - b[1])
  return f(Math.sqrt(f(f(x * x) + f(y * y))))
}
const safe_asinf = (a: number) => f(Math.asin(Math.max(-1, Math.min(1, a))))
function angle_normalized_v2v2(a: Vec2, b: Vec2) {
  if (dot_v2v2(a, b) >= 0) return f(2 * safe_asinf(f(len_v2v2(a, b) / 2)))
  return f(f(Math.PI) - f(2 * safe_asinf(f(len_v2v2(a, [-b[0], -b[1]]) / 2))))
}
export type AngleMouseInput = {
  center: Vec2; precision: boolean; precision_factor: number
  data: { angle: number; mval_prev: Vec2 }
}
'''
out = ROOT / 'packages/editor/src/components/scene-camera/rig-transform-angle-source.ts'
out.write_text('// SPDX-License-Identifier: GPL-2.0-or-later\n'
               '// Generated by scripts/blender/compile-transform-angle.py; do not edit.\n'
               + 'export const sourceAngleHashes = ' + json.dumps(hashes, indent=2) + '\n'
               + f'export const sourceAnglePrecision = Math.fround({precision})\n'
               + adapters + translated + '\n' + flip)
subprocess.run([str(ROOT / 'node_modules/.bin/biome'), 'format', '--write', str(out)], check=True, cwd=ROOT)

helpers = ['zero_v2', 'copy_v2_v2', 'sub_v2_v2v2', 'mul_v2_v2fl', 'negate_v2_v2',
           'dot_v2v2', 'cross_v2v2', 'len_v2v2', 'normalize_v2_v2_length',
           'normalize_v2_v2', 'normalize_v2']
harness = '''#include <cmath>
#include <iostream>
#include <iomanip>
#define MINLINE inline
#define BLI_ASSERT_UNIT_V2(x) ((void)0)
#define CLAMP(a, low, high) a = std::fmin(high, std::fmax(low, a))
namespace blender { struct float2 { float x, y; operator const float*() const { return &x; } }; }
struct TransInfo {};
struct InputAngle_Data { double angle; double mval_prev[2]; };
struct MouseInput { float center[2]; bool precision; float precision_factor; void* data; };
''' + '\n'.join(extract(inline, name) for name in helpers)
harness += '\n' + extract(safe, 'safe_asinf') + '\n' + extract(vector, 'angle_normalized_v2v2')
harness += '\n' + original + '''
int main() {
  MouseInput mi; InputAngle_Data data; mi.data = &data; mi.precision_factor = 1.0f / 30.0f;
  int count; double mval[2]; float output[3];
  while (std::cin >> mi.center[0] >> mi.center[1] >> data.mval_prev[0] >> data.mval_prev[1] >> count) {
    data.angle = 0;
    for (int i = 0; i < count; i++) {
      std::cin >> mval[0] >> mval[1] >> mi.precision;
      InputAngle(nullptr, &mi, mval, output);
      std::cout << std::setprecision(17) << output[0] << " " << data.angle << " "
                << data.mval_prev[0] << " " << data.mval_prev[1] << "\\n";
    }
  }
}
'''
cases = []
for center in [[400, 400], [400.75, 300.125], [-20.125, 50.5]]:
    for direction in [1, -1]:
        for radius in [160, 0.01]:
            steps = []
            for i in range(1, 73):
                angle = i * math.pi / 12 * direction
                steps.append({'point': [center[0] + radius * math.cos(angle), center[1] + radius * math.sin(angle)],
                              'precision': 13 <= i <= 36})
            cases.append({'center': center, 'origin': [center[0] + radius, center[1]], 'steps': steps})
cases += [
    {'center': [0, 0], 'origin': [0, 0], 'steps': [{'point': p, 'precision': False} for p in [[10, 0], [0, 10], [-10, 0]]]},
    {'center': [400, 400], 'origin': [560, 400], 'steps': [{'point': p, 'precision': False} for p in [[400, 400], [240, 400], [560, 400], [560, 400.001]]]},
]
inputs = []
for case in cases:
    inputs.append(' '.join(map(str, case['center'] + case['origin'] + [len(case['steps'])])))
    inputs.extend(' '.join(map(str, step['point'] + [int(step['precision'])])) for step in case['steps'])
with tempfile.TemporaryDirectory(prefix='blender-angle-') as directory:
    cpp, exe = Path(directory) / 'angle.cc', Path(directory) / 'angle'
    cpp.write_text(harness)
    subprocess.run(['clang++', '-std=c++17', '-ffp-contract=off', str(cpp), '-o', str(exe)], check=True)
    values = iter(subprocess.check_output([str(exe)], input='\n'.join(inputs), text=True).splitlines())
for case in cases:
    for step in case['steps']:
        value, accumulated, x, y = map(float, next(values).split())
        step.update(value=value, accumulated=accumulated, previous=[x, y])
assert next(values, None) is None
fixture = ROOT / 'tests/integration/fixtures/blender-transform-angle.json'
fixture.write_text(json.dumps({'hashes': hashes, 'cases': cases}, indent=2) + '\n')
print(f'Compiled original InputAngle and BLI math for {sum(len(c["steps"]) for c in cases)} native reference steps')
