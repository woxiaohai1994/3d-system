"""Extract Blender's bone hit priority, nested selection rectangles and segment clipping."""
from pathlib import Path
import hashlib, json, re, subprocess

ROOT = Path(__file__).resolve().parents[2]
DIRECTORY = ROOT / 'vendor/blender-rig-picking'
manifest = json.loads((DIRECTORY / 'UPSTREAM.json').read_text())
hashes = {}
def read(name):
    data = (DIRECTORY / name).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    assert digest == manifest['files'][name]['sha256']
    hashes[name] = digest
    return data.decode()

def block(source, start):
    brace = source.index('{', start)
    end, depth = brace + 1, 1
    while depth:
        depth += (source[end] == '{') - (source[end] == '}')
        end += 1
    return source[start:end]

armature = read('armature_select.cc')
function = block(armature, armature.index('static void *ed_armature_pick_bone_from_selectbuffer_impl'))
priority = block(function, function.index('if (data)'))
priority = priority.replace('*r_base = base;', '').replace('firstSel_base = base;', '').replace('firstunSel_base = base;', '')
priority = priority.replace('data', 'hit').replace('hit_result.depth', 'hit.depth')
priority = priority.replace('!firstSel', 'firstSel === null').replace('!firstunSel', 'firstunSel === null')
priority = re.sub(r'/\*.*?\*/', '', priority, flags=re.S)

view = read('view3d_select.cc')
function = block(view, view.index('static int mixed_bones_object_selectbuffer('))
radius = function[function.index('if (hits15 == 1)'):function.index('\nfinally:')]
radius = radius.replace('goto finally;', 'return hits;')
radius = re.sub(r'selectbuffer_ret_hits_(15|9|5)\([^;]+\)', lambda m: '14' if m[1] == '15' else m[1], radius)
radius = re.sub(r'selectbuffer_has_bones\([^;]+\)', 'true', radius)
radius = re.sub(r'BLI_rcti_init_pt_radius\([^;]+;', '', radius)
radius = re.sub(r'hits9 = view3d_opengl_select\([^;]+;', 'hits9 = counts[1];', radius)
radius = re.sub(r'hits5 = view3d_opengl_select\([^;]+;', 'hits5 = counts[2];', radius)
radius = re.sub(r'\s*(?:int ofs;|ofs = hits15;|ofs \+= hits9;)', '', radius)

geometry = read('math_geom.cc')
clip = block(geometry, geometry.index('bool clip_segment_v3_plane_n('))
clip = clip[clip.index('{')+1:-1]
clip = re.sub(r'/\*.*?\*/', '', clip, flags=re.S)
clip = clip.replace('float p1_fac', 'let p1_fac').replace('float t', 'let t')
clip = clip.replace('float dp[3];', 'const dp = p2.map((v, i) => v - p1[i]!) as V3;')
clip = clip.replace('sub_v3_v3v3(dp, p2, p1);', '')
clip = clip.replace('for (int i = 0; i < plane_num; i++)', 'for (let i = 0; i < plane_array.length; i++)')
clip = clip.replace('const float *plane = plane_array[i];', 'const plane = plane_array[i]!;')
clip = clip.replace('const float div', 'const div')
clip = clip.replace('dot_v3v3(dp, plane)', 'dp[0]*plane[0] + dp[1]*plane[1] + dp[2]*plane[2]')
clip = clip.replace('plane_point_side_v3(plane, p1)', '(plane[0]*p1[0] + plane[1]*p1[1] + plane[2]*p1[2] + plane[3])')
clip = clip.replace('return false;', 'return null;')
clip = clip[:clip.index('const float p1_copy')]
clip += 'return [p1.map((v,i) => v+dp[i]!*p1_fac) as V3, p1.map((v,i) => v+dp[i]!*p2_fac) as V3];'
clip = re.sub(r'(\d\.\d+)f', r'\1', clip)

query = read('wm_event_query.cc')
motion = block(query, query.index('bool WM_cursor_test_motion_and_update('))
motion = motion[motion.index('{')+1:-1]
motion = motion.replace('static int mval_prev[2] = {-1, -1};', '')
motion = motion.replace('bool use_cycle', 'const use_cycle')
motion = motion.replace('len_manhattan_v2v2_int(mval, mval_prev)', 'Math.abs(mval[0]-mval_prev[0])+Math.abs(mval[1]-mval_prev[1])')
motion = motion.replace('WM_EVENT_CURSOR_MOTION_THRESHOLD', 'sourceMoveThreshold * uiScale')
motion = motion.replace('copy_v2_v2_int(mval_prev, mval);', 'mval_prev[0]=mval[0]; mval_prev[1]=mval[1];')
threshold = int(re.search(r'\.move_threshold\s*=\s*(\d+)', read('userdef_default.c'))[1])
assert '#define WM_EVENT_CURSOR_MOTION_THRESHOLD ((float)U.move_threshold * UI_SCALE_FAC)' in read('WM_types.hh')
assert '#define UI_SCALE_FAC ((void)0, U.scale_factor)' in read('DNA_userdef_types.h')
pick = read('gpu_select_pick.cc')
compare = block(pick, pick.index('static int depth_cmp('))
compare = compare[compare.index('if ('):compare.rindex('}')]
compare = compare.replace('d1->depth', 'a.depth').replace('d2->depth', 'b.depth')
for name in manifest['files']:
    if name not in hashes:
        read(name)

output = '''// SPDX-License-Identifier: GPL-2.0-or-later
// Generated by scripts/blender/compile-rig-picking.py; do not edit.
type V3 = [number, number, number]
export type SourceBoneHit = { name: string; depth: number }
export function sourcePickBone<T extends SourceBoneHit>(hits: T[], selected: string[], do_nearest: boolean): T | null {
 let firstunSel: T | null = null, firstSel: T | null = null
 let takeNext = false, minsel = 0xffffffff, minunsel = 0xffffffff
 for (const hit of hits) {
  const sel = selected.includes(hit.name)
''' + priority + '''
 }
 return firstunSel ?? firstSel
}
export function sourcePickRadius(counts: [number, number, number]) {
 let hits = 0, hits15 = counts[0], hits9 = 0, hits5 = 0
 let has_bones15 = false, has_bones9 = false, has_bones5 = false
''' + radius + '''
 return hits
}
export function sourceClipSegment(p1: V3, p2: V3, plane_array: [number,number,number,number][]): [V3,V3] | null {
''' + clip + '\n}\nexport const sourceMoveThreshold = ' + str(threshold) + '''
export function sourceCursorHasMotion(mval: [number,number], mval_prev: [number,number], uiScale = 1): boolean {
''' + motion + '''
}
export function sourceHitDepthCompare(a: SourceBoneHit, b: SourceBoneHit): number {
''' + compare + '\n}\nexport const sourceRigPickingHashes = ' + json.dumps({name: hashes[name] for name in manifest['files']}, indent=2) + '\n'
out = ROOT / 'packages/editor/src/components/scene-camera/rig-picking-source.ts'
out.write_text(output.replace(' == ', ' === ').replace(' != ', ' !== '))
subprocess.run([str(ROOT/'node_modules/.bin/biome'), 'check', '--write', str(out)], check=True)
