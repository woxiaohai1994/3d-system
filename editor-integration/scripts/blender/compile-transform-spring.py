"""Translate the original spring callbacks; compile the same C++ for reference cases."""
from pathlib import Path
import hashlib
import json
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
path = ROOT / 'vendor/blender-transform-modes/transform_input.cc'
source = path.read_text()
digest = hashlib.sha256(path.read_bytes()).hexdigest()
upstream = json.loads((path.parent / 'UPSTREAM.json').read_text())
assert digest == upstream['files'][path.name]['sha256']


def extract(name):
    match = re.search(r'static void ' + name + r'\([^\{]+\)\s*\{', source)
    start, end, depth = match.start(), match.end(), 1
    while depth:
        depth += (source[end] == '{') - (source[end] == '}')
        end += 1
    return source[start:end]


names = ['InputSpring', 'InputSpringFlip', 'calcSpringFactor']
original = '\n\n'.join(extract(name) for name in names)
translated = original
translated = re.sub(r'static void (InputSpring(?:Flip)?)\([^\{]+\)',
                    r'export function \1(t: unknown, mi: SpringMouseInput, mval: readonly [number, number], output: [number, number, number])', translated)
translated = translated.replace('function InputSpring(t:', 'function InputSpring(_t:')
translated = translated.replace('static void calcSpringFactor(MouseInput *mi)',
                                'export function calcSpringFactor(mi: SpringMouseInput)')
translated = translated.replace('double dx, dy;', 'let dx: number, dy: number;')
translated = translated.replace('float ratio;', 'let ratio: number;')
translated = re.sub(r'float mdir\[2\] = \{(.*?)\};', r'const mdir = [\1];', translated)
translated = translated.replace('mi->', 'mi.')
translated = translated.replace(' == ', ' === ')
translated = re.sub(r'\bdouble\(', 'Number(', translated)
translated = re.sub(r'\bfloat\(', 'Math.fround(', translated)
translated = re.sub(r'\bint\(', 'Math.trunc(', translated)
translated = re.sub(r'\bhypot\(', 'Math.hypot(', translated)
translated = re.sub(r'(\d+\.\d+)f\b', r'\1', translated)
translated = re.sub(r'ratio = (.*?);', r'ratio = Math.fround(\1);', translated)
assert '->' not in translated and 'static void' not in translated
out = ROOT / 'packages/editor/src/components/scene-camera/rig-transform-spring-source.ts'
out.write_text('''// SPDX-License-Identifier: GPL-2.0-or-later
// Generated by scripts/blender/compile-transform-spring.py; do not edit.
export type SpringMouseInput = { center: [number, number]; imval: [number, number]; factor: number }
const int64_t = (value: number) => BigInt(Math.trunc(value))
const len_v2 = (v: number[]) => Math.fround(Math.sqrt(Math.fround(Math.fround(v[0]! * v[0]!) + Math.fround(v[1]! * v[1]!))))
''' + f'export const sourceSpringHash = {json.dumps(digest)}\n' + translated + '\n')
subprocess.run([str(ROOT / 'node_modules/.bin/biome'), 'format', '--write', str(out)], check=True, cwd=ROOT)

# Execute the unmodified function bodies with only their C structs/math dependencies.
harness = '''#include <cmath>
#include <cstdint>
#include <iostream>
#include <iomanip>
using std::hypot;
struct TransInfo {};
struct MouseInput { float center[2], imval[2], factor; };
static float len_v2(const float v[2]) { return std::sqrt(v[0]*v[0] + v[1]*v[1]); }
''' + original + '''
int main() {
  MouseInput mi; double mval[2]; float output[3];
  while (std::cin >> mi.center[0] >> mi.center[1] >> mi.imval[0] >> mi.imval[1] >> mval[0] >> mval[1]) {
    calcSpringFactor(&mi); InputSpringFlip(nullptr, &mi, mval, output);
    std::cout << std::setprecision(10) << output[0] << "\\n";
  }
}
'''
cases = []
for center in [[400, 400], [400.75, 300.125], [0, 0]]:
    for delta in [[160, 0], [0, 0], [0.125, -0.25], [-200, 70]]:
        origin = [center[i] + delta[i] for i in range(2)]
        for current in [[610, 400], [240, 400], center, [400.5, 300.1], [-100, -200]]:
            cases.append({'center': center, 'origin': origin, 'current': current})
with tempfile.TemporaryDirectory(prefix='blender-spring-') as directory:
    cpp, exe = Path(directory) / 'spring.cc', Path(directory) / 'spring'
    cpp.write_text(harness)
    subprocess.run(['clang++', '-std=c++17', '-ffp-contract=off', str(cpp), '-o', str(exe)], check=True)
    inputs = '\n'.join(' '.join(map(str, c['center'] + c['origin'] + c['current'])) for c in cases)
    values = subprocess.check_output([str(exe)], input=inputs, text=True).splitlines()
assert len(cases) == len(values)
for case, value in zip(cases, values):
    case['value'] = float(value)
fixture = ROOT / 'tests/integration/fixtures/blender-transform-spring.json'
fixture.write_text(json.dumps({'hash': digest, 'cases': cases}, indent=2) + '\n')
print(f'Compiled original spring callbacks and {len(cases)} native C++ reference cases')
