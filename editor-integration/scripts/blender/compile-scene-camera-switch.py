"""Translate the upstream scalar/list camera-switch function, retaining its body."""
import hashlib
from pathlib import Path
import re

root = Path(__file__).resolve().parents[2]
source = (root / 'vendor/blender-scene-camera/scene.cc').read_text()
start = source.index('Object *BKE_scene_camera_switch_find(Scene *scene)')
end = source.index('\n#endif', start)
body = source[start:end]
body = body.replace('Object *BKE_scene_camera_switch_find(Scene *scene)',
                    'export function sourceSceneCameraSwitch(scene: SourceCameraScene): SourceCameraRef | null')
body = body.replace('LISTBASE_FOREACH (TimeMarker *, m, &scene->markers)',
                    'for (const m of scene.markers)')
body = body.replace('const int ctime = int(BKE_scene_ctime_get(scene));',
                    'const ctime = Math.trunc(scene.frame);')
body = re.sub(r'\bint (\w+) =', r'let \1 =', body)
body = re.sub(r'Object \*(\w+) =', r'let \1: SourceCameraRef | null =', body)
body = body.replace('->', '.').replace('nullptr', 'null')
if any(token in body for token in ['Object *', 'TimeMarker *', 'BKE_scene_ctime_get', 'LISTBASE_FOREACH']):
    raise ValueError('Untranslated upstream camera switch syntax')
header = '''// SPDX-License-Identifier: GPL-2.0-or-later
// Generated by scripts/blender/compile-scene-camera-switch.py; do not edit.
export type SourceCameraRef = { id: string; visibility_flag: number }
export type SourceCameraScene = {
  r: { mode: number }; frame: number;
  markers: { frame: number; camera: SourceCameraRef | null }[];
}
const MAXFRAME = 1048574
const R_NO_CAMERA_SWITCH = 1
const OB_HIDE_RENDER = 1
'''
output = root / 'packages/core/src/lib/blender-scene-camera-source.ts'
output.write_text(header + 'export const sceneCameraSourceHash = "' +
                  hashlib.sha256(source.encode()).hexdigest() + '"\n' + body + '\n')
print(output)
